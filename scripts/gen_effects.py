# Generate src/data/effects.ts from the original app's parser worker bundle.
# The bundle is parsed as data only. Do not execute code from it.
# Usage:
#   curl -sL https://mustang.artnettune.com/assets/parser.worker-Bq5b7bMG.js -o /tmp/parser.worker.js
#   python3 -I scripts/gen_effects.py /tmp/parser.worker.js src/data/effects.ts
# The worker file name has a build hash. If the URL fails, look up the current name in
# https://mustang.artnettune.com/assets/routes-*.js (linked from the site's index.html).
# The anchors below ('u=[{id:0,...', ';function d(e,t)') match that minified build only.
# Recovered from the Claude Code session of 2026-10-25.
import json, re, sys
src = open(sys.argv[1]).read()
i = src.index('u=[{id:0,name:`Empty`,family:`stomp`')
j = src.index(';function d(e,t)')
seg = src[i + 2 : j]  # starts at '['
UNK = {'r': [0, 1, 1], 'i': [1, 8, 1], 'a': [8, 8, 1], 'o': [1, 1, 1], 's': [1, 8, 1], 'c': [2, 1, 1], 'l': [0, 8, 1]}

# the reverb block is generated by a .map(); pull its rows out and expand them by hand
m = re.search(r',\.\.\.\[(\[.*?\])\]\.map\(.*?\)\)', seg, flags=re.S)
rows = re.findall(r'\[(\d+),`([^`]*)`,`([^`]*)`\]', m.group(1))
seg = seg.replace(m.group(0), '')
seg = seg.rstrip().rstrip(']').rstrip() + ']'

def to_json(t):
    t = re.sub(r'`([^`]*)`', lambda k: json.dumps(k.group(1)), t)
    t = t.replace('!0', 'true').replace('!1', 'false')
    t = re.sub(r'unknown:([a-z])\b', lambda k: 'unknown:' + json.dumps(UNK[k.group(1)]), t)
    t = re.sub(r'([{,])([A-Za-z_]\w*):', r'\1"\2":', t)
    t = re.sub(r'([{,])(\d+):', r'\1"\2":', t)
    return t

items = json.loads(to_json(seg))
for rid, name, based in rows:
    items.append({'id': int(rid), 'name': name, 'basedOn': based, 'family': 'reverb',
                  'knobs': ['Level', 'Decay', 'Dwell', 'Diffusion', 'Tone'], 'unknown': UNK['l']})

def q(s):
    return "'" + s.replace('\\', '\\\\').replace("'", "\\'") + "'"

out = """import type { EffectFamily } from '../protocol/packets'

export interface EffectModel {
  id: number
  name: string
  basedOn?: string
  family: EffectFamily
  /** Labels of the knobs the effect uses, in packet order (bytes 32..). */
  knobs: string[]
  /** Knobs that pick from named choices instead of a 0-100 value, keyed by knob index. */
  enums?: Record<number, string[]>
  /** Three bytes the amp reports for the effect. The original editor stores them but does not write them. */
  unknown: [number, number, number]
  v2Only?: boolean
}

export const EFFECTS: EffectModel[] = [
"""
for e in items:
    parts = ['id: %d' % e['id'], 'name: ' + q(e['name'])]
    if e.get('basedOn'): parts.append('basedOn: ' + q(e['basedOn']))
    parts += ["family: '%s'" % e['family'], 'knobs: [%s]' % ', '.join(q(k) for k in e['knobs'])]
    if e.get('enums'):
        parts.append('enums: { %s }' % ', '.join('%s: [%s]' % (k, ', '.join(q(x) for x in v)) for k, v in e['enums'].items()))
    parts.append('unknown: [%s]' % ', '.join(str(x) for x in e['unknown']))
    if e.get('v2Only'): parts.append('v2Only: true')
    out += '  { %s },\n' % ', '.join(parts)
out += """]

export const FAMILY_LABELS: Record<EffectFamily, string> = {
  stomp: 'Stompbox', mod: 'Modulation', delay: 'Delay', reverb: 'Reverb',
}

/** Effects offered for a family. v1 firmware hides the models that only exist on v2. */
export const effectsFor = (family: EffectFamily, isV2: boolean) =>
  EFFECTS.filter((e) => e.family === family && (isV2 || !e.v2Only))

export const effectById = (family: EffectFamily, id: number) =>
  EFFECTS.find((e) => e.family === family && e.id === id)
"""
open(sys.argv[2], 'w').write(out)
from collections import Counter
print(len(items), dict(Counter(e['family'] for e in items)))
